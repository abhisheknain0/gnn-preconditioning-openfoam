"""Utilities to write predicted fields back into OpenFOAM field files."""

from __future__ import annotations

import re
from pathlib import Path

import torch

_HEADER_FORMAT_RE = re.compile(r"^\s*format\s+(\w+)\s*;", flags=re.MULTILINE)
_UNIFORM_VECTOR_RE = re.compile(
    r"internalField\s+uniform\s*\(\s*([^\s()]+)\s+([^\s()]+)\s+([^\s()]+)\s*\)\s*;",
    flags=re.DOTALL,
)
_UNIFORM_SCALAR_RE = re.compile(
    r"internalField\s+uniform\s+([^\s;()]+)\s*;",
    flags=re.DOTALL,
)


def _force_ascii_format(field_text: str) -> str:
    """
    Ensure OpenFOAM field header uses ASCII format.

    Our writer emits ASCII nonuniform lists; keeping `format binary;` in the
    header causes OpenFOAM parse failures.
    """
    pattern = re.compile(r"(^\s*format\s+)(ascii|binary)(\s*;)", re.MULTILINE)
    if not pattern.search(field_text):
        return field_text
    return pattern.sub(r"\1ascii\3", field_text, count=1)


def _header_format(field_text: str) -> str | None:
    match = _HEADER_FORMAT_RE.search(field_text)
    if match is None:
        return None
    return match.group(1).strip().lower()


def _replace_internal_field(template_text: str, new_internal_field_block: str) -> str:
    """
    Replace the `internalField` section while keeping all other content intact.

    This expects a standard OpenFOAM field file with a `boundaryField` section.
    """
    pattern = re.compile(r"internalField\s+.*?;\s*\n\s*boundaryField", re.DOTALL)
    replacement = f"{new_internal_field_block}\n\nboundaryField"
    if not pattern.search(template_text):
        raise ValueError("Could not find an `internalField ... boundaryField` section in template")
    return pattern.sub(replacement, template_text, count=1)


def read_openfoam_nonuniform_internal_size(field_path: str | Path) -> int:
    """
    Read the internalField length from an OpenFOAM nonuniform field file.

    Supports both scalar and vector nonuniform internal fields.
    """
    field_path = Path(field_path)
    # Use latin-1 to safely decode files that may contain binary payloads
    # after the ASCII header (common in OpenFOAM `format binary` fields).
    text = field_path.read_bytes().decode("latin-1", errors="ignore")
    pattern = re.compile(
        r"internalField\s+nonuniform\s+List<[^>]+>\s*(\d+)\s*\(",
        re.DOTALL,
    )
    match = pattern.search(text)
    if not match:
        raise ValueError(
            f"Could not parse nonuniform internalField size from {field_path}. "
            "Ensure the file contains `internalField nonuniform List<...>`."
        )
    return int(match.group(1))


def read_openfoam_nonuniform_vector_internal_field(field_path: str | Path) -> torch.Tensor:
    """
    Parse an OpenFOAM `internalField nonuniform List<vector>` as (N,3) tensor.

    This is intended for files like `0/C` generated by:
      postProcess -func writeCellCentres -time 0 -case <case>
    """
    field_path = Path(field_path)
    text = field_path.read_bytes().decode("latin-1", errors="ignore")
    header_fmt = re.search(r"^\s*format\s+(\w+)\s*;", text, flags=re.MULTILINE)
    if header_fmt and header_fmt.group(1).lower() == "binary":
        raise ValueError(
            f"{field_path} is `format binary`, but Python parser expects ASCII vectors. "
            "Regenerate cell centers in ASCII (e.g. set writeFormat ascii, then run "
            "`postProcess -func writeCellCentres -time 0 -case <case>`)."
        )
    pattern = re.compile(
        r"internalField\s+nonuniform\s+List<vector>\s*(\d+)\s*\(\s*(.*?)\s*\)\s*;",
        re.DOTALL,
    )
    match = pattern.search(text)
    if not match:
        raise ValueError(
            f"Could not parse `internalField nonuniform List<vector>` from {field_path}"
        )

    expected_n = int(match.group(1))
    body = match.group(2)
    vec_pattern = re.compile(
        r"\(\s*([^\s()]+)\s+([^\s()]+)\s+([^\s()]+)\s*\)"
    )
    vectors = vec_pattern.findall(body)
    if len(vectors) != expected_n:
        raise ValueError(
            f"Vector count mismatch in {field_path}: parsed {len(vectors)}, expected {expected_n}"
        )

    out = torch.empty((expected_n, 3), dtype=torch.float32)
    for i, (x, y, z) in enumerate(vectors):
        out[i, 0] = float(x)
        out[i, 1] = float(y)
        out[i, 2] = float(z)
    return out


def read_openfoam_nonuniform_scalar_internal_field(field_path: str | Path) -> torch.Tensor:
    """
    Parse an OpenFOAM `internalField nonuniform List<scalar>` as (N,) tensor.
    """
    field_path = Path(field_path)
    text = field_path.read_bytes().decode("latin-1", errors="ignore")
    header_fmt = _header_format(text)
    if header_fmt == "binary":
        raise ValueError(
            f"{field_path} is `format binary`, but Python parser expects ASCII scalars. "
            "Regenerate with writeFormat ascii before parsing."
        )

    pattern = re.compile(
        r"internalField\s+nonuniform\s+List<scalar>\s*(\d+)\s*\(\s*(.*?)\s*\)\s*;",
        re.DOTALL,
    )
    match = pattern.search(text)
    if not match:
        raise ValueError(
            f"Could not parse `internalField nonuniform List<scalar>` from {field_path}"
        )

    expected_n = int(match.group(1))
    body = match.group(2)
    values = re.findall(r"([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)", body)
    if len(values) != expected_n:
        raise ValueError(
            f"Scalar count mismatch in {field_path}: parsed {len(values)}, expected {expected_n}"
        )
    out = torch.tensor([float(v) for v in values], dtype=torch.float32)
    return out


def read_openfoam_vector_internal_field(
    field_path: str | Path,
    expected_size: int | None = None,
) -> torch.Tensor:
    """
    Read OpenFOAM vector internalField as (N,3) tensor.

    Supports:
    - `internalField nonuniform List<vector> ...`
    - `internalField uniform (ux uy uz);` (requires expected_size)
    """
    field_path = Path(field_path)
    text = field_path.read_bytes().decode("latin-1", errors="ignore")
    header_fmt = _header_format(text)

    if re.search(r"internalField\s+nonuniform\s+List<vector>", text):
        return read_openfoam_nonuniform_vector_internal_field(field_path)

    match = _UNIFORM_VECTOR_RE.search(text)
    if match is None:
        raise ValueError(
            f"Could not parse vector internalField from {field_path}. "
            "Expected uniform or nonuniform List<vector>."
        )
    if expected_size is None:
        raise ValueError(
            f"{field_path} has uniform vector internalField; provide expected_size for expansion."
        )
    if int(expected_size) <= 0:
        raise ValueError(f"expected_size must be > 0, got {expected_size}")

    if header_fmt == "binary":
        # Uniform values are still textual in header blocks; this is safe.
        pass

    ux = float(match.group(1))
    uy = float(match.group(2))
    uz = float(match.group(3))
    out = torch.empty((int(expected_size), 3), dtype=torch.float32)
    out[:, 0] = ux
    out[:, 1] = uy
    out[:, 2] = uz
    return out


def read_openfoam_scalar_internal_field(
    field_path: str | Path,
    expected_size: int | None = None,
) -> torch.Tensor:
    """
    Read OpenFOAM scalar internalField as (N,) tensor.

    Supports:
    - `internalField nonuniform List<scalar> ...`
    - `internalField uniform p;` (requires expected_size)
    """
    field_path = Path(field_path)
    text = field_path.read_bytes().decode("latin-1", errors="ignore")
    header_fmt = _header_format(text)

    if re.search(r"internalField\s+nonuniform\s+List<scalar>", text):
        return read_openfoam_nonuniform_scalar_internal_field(field_path)

    match = _UNIFORM_SCALAR_RE.search(text)
    if match is None:
        raise ValueError(
            f"Could not parse scalar internalField from {field_path}. "
            "Expected uniform or nonuniform List<scalar>."
        )
    if expected_size is None:
        raise ValueError(
            f"{field_path} has uniform scalar internalField; provide expected_size for expansion."
        )
    if int(expected_size) <= 0:
        raise ValueError(f"expected_size must be > 0, got {expected_size}")

    if header_fmt == "binary":
        # Uniform value lives in textual header; expansion is safe.
        pass

    val = float(match.group(1))
    out = torch.full((int(expected_size),), val, dtype=torch.float32)
    return out


def build_nearest_xy_index_map(
    source_xy: torch.Tensor,
    target_xy: torch.Tensor,
    chunk_size: int = 2048,
) -> tuple[torch.Tensor, dict[str, float]]:
    """
    Build nearest-neighbor index map from source points to target points in XY.

    Returns:
      - nn_index: (N_target,) long tensor, where nn_index[j] is source row for target j
      - distance_stats: summary of nearest XY distances
    """
    if source_xy.ndim != 2 or source_xy.shape[1] != 2:
        raise ValueError(f"source_xy must have shape (N,2), got {tuple(source_xy.shape)}")
    if target_xy.ndim != 2 or target_xy.shape[1] != 2:
        raise ValueError(f"target_xy must have shape (M,2), got {tuple(target_xy.shape)}")

    src = source_xy.detach().cpu().to(torch.float32)
    tgt = target_xy.detach().cpu().to(torch.float32)

    if src.shape[0] == 0 or tgt.shape[0] == 0:
        raise ValueError("source_xy and target_xy must be non-empty")

    try:
        # Fast path when scipy is available.
        from scipy.spatial import cKDTree  # type: ignore

        tree = cKDTree(src.numpy())
        distances, nn_index_np = tree.query(tgt.numpy(), k=1)
        nn_index = torch.as_tensor(nn_index_np, dtype=torch.long)
        d = torch.as_tensor(distances, dtype=torch.float32)
    except Exception:
        # Fallback without scipy dependency: chunked torch distance computation.
        n_target = tgt.shape[0]
        nn_index = torch.empty((n_target,), dtype=torch.long)
        d = torch.empty((n_target,), dtype=torch.float32)
        for start in range(0, n_target, max(1, int(chunk_size))):
            end = min(start + max(1, int(chunk_size)), n_target)
            chunk = tgt[start:end]  # (B,2)
            dist2 = torch.sum((chunk[:, None, :] - src[None, :, :]) ** 2, dim=2)  # (B,Nsrc)
            min_dist2, idx = torch.min(dist2, dim=1)
            nn_index[start:end] = idx
            d[start:end] = torch.sqrt(min_dist2)

    stats = {
        "min": float(d.min().item()),
        "max": float(d.max().item()),
        "mean": float(d.mean().item()),
        "median": float(torch.median(d).item()),
    }
    return nn_index, stats


def expand_surface_predictions_to_cell_centers_xy(
    surface_pos: torch.Tensor,
    cell_centers: torch.Tensor,
    velocity: torch.Tensor,
    pressure: torch.Tensor,
    chunk_size: int = 2048,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, dict[str, float]]:
    """
    Expand surface-node predictions to all OpenFOAM cell centers via XY nearest neighbor.

    Intended for one-cell-thick symmetry cases where the model predicts on a 2D
    surface mesh and OpenFOAM expects volume internalField values.
    """
    if surface_pos.ndim != 2 or surface_pos.shape[1] < 2:
        raise ValueError(f"surface_pos must have shape (N,>=2), got {tuple(surface_pos.shape)}")
    if cell_centers.ndim != 2 or cell_centers.shape[1] < 2:
        raise ValueError(
            f"cell_centers must have shape (M,>=2), got {tuple(cell_centers.shape)}"
        )
    if velocity.ndim != 2 or velocity.shape[0] != surface_pos.shape[0]:
        raise ValueError(
            "velocity must have shape (N,2|3) and match surface_pos rows, "
            f"got {tuple(velocity.shape)} vs {tuple(surface_pos.shape)}"
        )

    if pressure.ndim == 2 and pressure.shape[1] == 1:
        pressure = pressure.squeeze(-1)
    if pressure.ndim != 1 or pressure.shape[0] != surface_pos.shape[0]:
        raise ValueError(
            "pressure must have shape (N,) or (N,1) and match surface_pos rows, "
            f"got {tuple(pressure.shape)} vs {tuple(surface_pos.shape)}"
        )

    nn_index, stats = build_nearest_xy_index_map(
        source_xy=surface_pos[:, :2],
        target_xy=cell_centers[:, :2],
        chunk_size=chunk_size,
    )

    vel_cells = velocity.detach().cpu()[nn_index]
    p_cells = pressure.detach().cpu()[nn_index]
    return vel_cells, p_cells, nn_index, stats


def _format_vector_internal_field(velocity: torch.Tensor) -> str:
    """
    Format velocity values as OpenFOAM `nonuniform List<vector>`.

    Input:
      velocity: (N,2) or (N,3)
    """
    if velocity.ndim != 2 or velocity.shape[1] not in (2, 3):
        raise ValueError(f"velocity must have shape (N,2) or (N,3), got {tuple(velocity.shape)}")

    vel = velocity.detach().cpu().to(torch.float64)
    if vel.shape[1] == 2:
        zeros = torch.zeros((vel.shape[0], 1), dtype=vel.dtype)
        vel = torch.cat([vel, zeros], dim=1)

    lines = [f"({u:.16g} {v:.16g} {w:.16g})" for u, v, w in vel.tolist()]
    body = "\n".join(lines)
    return (
        "internalField   nonuniform List<vector>\n"
        f"{vel.shape[0]}\n"
        "(\n"
        f"{body}\n"
        ")\n"
        ";"
    )


def _format_scalar_internal_field(pressure: torch.Tensor) -> str:
    """
    Format pressure values as OpenFOAM `nonuniform List<scalar>`.

    Input:
      pressure: (N,) or (N,1)
    """
    if pressure.ndim == 2 and pressure.shape[1] == 1:
        pressure = pressure.squeeze(-1)
    if pressure.ndim != 1:
        raise ValueError(f"pressure must have shape (N,) or (N,1), got {tuple(pressure.shape)}")

    p = pressure.detach().cpu().to(torch.float64)
    lines = [f"{x:.16g}" for x in p.tolist()]
    body = "\n".join(lines)
    return (
        "internalField   nonuniform List<scalar>\n"
        f"{p.shape[0]}\n"
        "(\n"
        f"{body}\n"
        ")\n"
        ";"
    )


def _scatter_to_internal_order(values: torch.Tensor, index_map: torch.Tensor, name: str) -> torch.Tensor:
    """
    Scatter predictions into OpenFOAM internal ordering.

    `index_map[i]` is the target internal index for source row `i`.
    """
    if index_map.ndim != 1:
        raise ValueError(f"{name} index_map must be 1D, got shape {tuple(index_map.shape)}")
    if values.shape[0] != index_map.shape[0]:
        raise ValueError(
            f"{name} size mismatch: values has {values.shape[0]} rows, "
            f"index_map has {index_map.shape[0]}"
        )

    index_map = index_map.to(torch.long).detach().cpu()
    values = values.detach().cpu()

    if index_map.numel() == 0:
        return values

    min_idx = int(index_map.min().item())
    max_idx = int(index_map.max().item())
    if min_idx < 0:
        raise ValueError(f"{name} index_map contains negative indices (min={min_idx})")
    if max_idx >= index_map.numel():
        raise ValueError(
            f"{name} index_map out of range: max={max_idx}, expected < {index_map.numel()} "
            "(use dense 0..N-1 internal indexing)"
        )
    if torch.unique(index_map).numel() != index_map.numel():
        raise ValueError(f"{name} index_map must be one-to-one (duplicate internal indices found)")

    out = torch.empty_like(values)
    out[index_map] = values
    return out


def write_openfoam_initial_fields(
    output_dir: str | Path,
    velocity: torch.Tensor,
    pressure: torch.Tensor,
    u_template_path: str | Path,
    p_template_path: str | Path,
    index_map: torch.Tensor | None = None,
    expected_internal_size: int | None = None,
) -> tuple[Path, Path]:
    """
    Write predicted `U` and `p` fields using OpenFOAM templates.

    Notes:
      - Boundary conditions are copied from the template files.
      - Only `internalField` is replaced.
      - If `index_map` is provided, values are scattered into OpenFOAM internal order.
      - Otherwise, ordering must already match OpenFOAM field ordering.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    u_template_path = Path(u_template_path)
    p_template_path = Path(p_template_path)

    if not u_template_path.exists():
        raise FileNotFoundError(f"U template not found: {u_template_path}")
    if not p_template_path.exists():
        raise FileNotFoundError(f"p template not found: {p_template_path}")

    if index_map is not None:
        velocity = _scatter_to_internal_order(velocity, index_map, name="velocity")
        pressure = _scatter_to_internal_order(pressure, index_map, name="pressure")

    if expected_internal_size is not None:
        expected_internal_size = int(expected_internal_size)
        if velocity.shape[0] != expected_internal_size:
            raise ValueError(
                f"velocity length mismatch: got {velocity.shape[0]}, expected {expected_internal_size}"
            )
        p_rows = pressure.shape[0] if pressure.ndim > 1 else pressure.numel()
        if p_rows != expected_internal_size:
            raise ValueError(
                f"pressure length mismatch: got {p_rows}, expected {expected_internal_size}"
            )

    velocity_block = _format_vector_internal_field(velocity)
    pressure_block = _format_scalar_internal_field(pressure)

    u_template = u_template_path.read_text(encoding="utf-8")
    p_template = p_template_path.read_text(encoding="utf-8")

    # We always emit ASCII internalField blocks; align header format to avoid
    # binary-block parse errors in OpenFOAM.
    u_template = _force_ascii_format(u_template)
    p_template = _force_ascii_format(p_template)

    u_text = _replace_internal_field(u_template, velocity_block)
    p_text = _replace_internal_field(p_template, pressure_block)

    u_out = output_dir / "U"
    p_out = output_dir / "p"
    u_out.write_text(u_text, encoding="utf-8")
    p_out.write_text(p_text, encoding="utf-8")

    return u_out, p_out
